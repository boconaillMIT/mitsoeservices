SELECT PROFIT_CENTER_ID,PROFIT_CENTER_NAME,IS_CLOSED_COST_COLLECTOR,COUNT(*) AS ACCOUNTS,
       COUNT(DISTINCT COST_COLLECTOR_ID) AS DISTINCT_ACCOUNTS
FROM WAREUSER.COST_COLLECTORS_ACCESSIBLE
WHERE PROFIT_CENTER_ID IN (:profit_center,'P'||:profit_center)
GROUP BY PROFIT_CENTER_ID,PROFIT_CENTER_NAME,IS_CLOSED_COST_COLLECTOR
ORDER BY PROFIT_CENTER_ID,IS_CLOSED_COST_COLLECTOR
